"""
ВЕТВИ РАЗВИТИЯ — ДАННЫЕ (M11/M12).

Здесь два слоя:
  * SKILL_TREES — отдельное древо каждого оружия (обычно три ветви; у
    пистолета и метлы — по четыре);
  * PLAYER_TREE — общее древо героя, не привязанное к экипировке.
Все они лежат на одной доске skill_board.py и покупаются через UI.

Философия (документ по дизайну):
  * узлы — это не «ещё один класс», а запИСИ: параметры модификаторов
    и ключи механик; правила покупки — в skill_tree.py, поведение
    механик — в weapons/projectiles/game;
  * каждая ветвь — СТРАТЕГИЯ, а не набор цифр (см. desc узлов);
  * три типа узлов:
      tier 1..3 — «модификаторы» и «механики»;
      tier 4    — «ключевая способность»;
      tier 5    — ПАРА взаимоисключающих доктрин (skill_capstones.py).
                 Доктрины меняют стиль боя, а не только числа, и могут
                 требовать соседний навык из другой ветви.
      tier 6    — дополнительные специализации пистолета после выбранной
                 доктрины, с перекрёстными условиями внутри его древа.

Структура узла:
    id     — уникальный ключ (попадает в weapon.nodes при покупке);
    name   — имя в магазине;
    tier   — уровень внутри ветви (1..5, покупается по порядку);
    cost   — базовая цена в монетах;
    desc   — короткое пояснение для UI (одна строка!);
    apply  — ЧИСЛОВЫЕ модификаторы spec: "damage_mul"/"cooldown_mul"/
             "spread_deg_add"/"pellets_add"/"ammo_cost_add" ...
             именуют КЛЮЧИ spec (ключ + суффикс _mul/_add);
             применяются ОДИН РАЗ при покупке (как старая прокачка);
    mods   — МЕХАНИКИ: складываются в weapon.mods (dict), читаются
             при сборке снаряда (resolve_shot) и в обработке попаданий;
    requires — явные обязательные узлы (гибридные доктрины);
    excludes — парная доктрина, которую навсегда закрывает этот выбор;
    hybrid   — узел требует соседнюю ветвь и потому дороже на 15%;
    lane     — сторона развилки tier 5 (-1 / +1) для геометрии доски;
    training — (школа, уровень) подготовки другого оружия;
    mode     — режим пистолета, который открывает узел;
    no_main  — узел-вход не фиксирует основную ветвь.

Почему «складываются»: покупая Т1 и Т3 одной ветви, игрок получает
оба эффекта сразу — комбинации не нужно писать руками (комбинационного
взрыва нет: механика = независимый эффект, а не новый класс).
"""
